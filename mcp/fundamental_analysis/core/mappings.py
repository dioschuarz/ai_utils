from typing import Dict, List, TypedDict, Optional

def normalize_sector(sector: str) -> str:
    s = sector.lower().strip()
    if "tech" in s:
        return "Information Technology"
    if "health" in s:
        return "Health Care"
    if "financial" in s:
        return "Financials"
    if "basic" in s or "material" in s:
        return "Materials"
    if "defensive" in s or "staple" in s:
        return "Consumer Staples"
    if "cyclical" in s or "discretionary" in s:
        return "Consumer Discretionary"
    if "comm" in s:
        return "Communication Services"
    return sector.title()

def find_gics_sub_industry(sector: str, industry: str) -> Optional[str]:
    """
    Find GICS sub-industry ID (8-digit string) by matching YFinance sector and industry text.
    """
    if not sector:
        return None
    norm_sector = normalize_sector(sector)
    
    # 1. Substring match on sub_industry_name
    if industry:
        ind_lower = industry.lower().strip()
        for sub_id, mappings in GICS_MAPPINGS.items():
            if not mappings:
                continue
            first = mappings[0]
            if first['sector'].lower() == norm_sector.lower():
                sub_name_lower = first['sub_industry_name'].lower()
                if sub_name_lower in ind_lower or ind_lower in sub_name_lower:
                    return sub_id

        # 2. Try match on GICS industry name
        for sub_id, mappings in GICS_MAPPINGS.items():
            if not mappings:
                continue
            first = mappings[0]
            if first['sector'].lower() == norm_sector.lower():
                gics_ind_lower = first['industry'].lower()
                if gics_ind_lower in ind_lower or ind_lower in gics_ind_lower:
                    return sub_id

    # 3. Fallback: return the first sub-industry in that sector
    for sub_id, mappings in GICS_MAPPINGS.items():
        if not mappings:
            continue
        if mappings[0]['sector'].lower() == norm_sector.lower():
            return sub_id
            
    return "10101010" # Default fallback


